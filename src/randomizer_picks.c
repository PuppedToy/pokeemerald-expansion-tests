static u16 PickItemAt(u16 pickIndex, u16 slot)
{
    if (pickIndex >= PICK_COUNT || slot >= MAX_PICK_ITEMS)
        return ITEM_NONE;
    return gItemPicks[pickIndex].items[slot];
}

void GetItemPickItem(void)
{
    gSpecialVar_Result = PickItemAt(gSpecialVar_0x8004, gSpecialVar_0x8005);
}

static const u8 sText_TMPrefix[] = _("TM ");

void BufferItemPickName(void)
{
    u16 item = PickItemAt(gSpecialVar_0x8004, gSpecialVar_0x8005);

    if (GetItemPocket(item) == POCKET_TM_HM && ItemIdToBattleMoveId(item) != MOVE_NONE)
    {
        // "TM <move>" — resolves through gTMHMItemMoveIds, so labels follow the injected TM table.
        StringCopy(gStringVar1, sText_TMPrefix);
        StringAppend(gStringVar1, GetMoveName(ItemIdToBattleMoveId(item)));
    }
    else
    {
        CopyItemName(item, gStringVar1);
    }
}

