bool32 RandomizerIsHiddenMegaObject(const struct ObjectEventTemplate *template)
{
    u32 i;

    for (i = 0; i < MEGA_TRAINER_COUNT; i++)
    {
        if (!gMegaTrainerHidden[i])
            continue;
        if (template->script == sMegaTrainerObjects[i].trainerScript)
            return TRUE;
        if (template->flagId == sMegaTrainerObjects[i].ballFlag)
            return TRUE;
    }
    return FALSE;
}
